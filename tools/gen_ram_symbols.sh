#!/usr/bin/env bash
# Regenerates src/eb_ram.h from the ebsrc disassembly's RAM layout.
# Needs: git, make, a C compiler. Builds cc65 v2.19 (the version ebsrc targets) into a temp dir.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WORK="${WORK:-$(mktemp -d)}"
[ -d "$WORK/cc65" ]  || git clone -q --depth 1 --branch V2.19 https://github.com/cc65/cc65 "$WORK/cc65"
[ -x "$WORK/cc65/bin/ca65" ] || make -C "$WORK/cc65" -j8 bin >/dev/null
[ -d "$WORK/ebsrc" ] || git clone -q --depth 1 https://github.com/Herringway/ebsrc "$WORK/ebsrc"

cat > "$WORK/ram.cfg" <<'CFG'
MEMORY {
    BSS:  start = $7E0000, size = $B800, file = "";
    RAM2: start = $7EB800, size = $14800, file = "";
}
SEGMENTS {
    RAM1: load = BSS, type = bss;
    RAM2: load = RAM2, type = bss;
}
CFG
(cd "$WORK/ebsrc" && "$WORK/cc65/bin/ca65" -g -t none --cpu 65816 -D USA \
    --include-dir include --include-dir src -o "$WORK/ram.o" src/bankconfig/common/ram.asm)
"$WORK/cc65/bin/ld65" -C "$WORK/ram.cfg" -Ln "$WORK/labels.txt" -o /dev/null "$WORK/ram.o"

# Ask the assembler for game_state field offsets instead of trusting comments.
FIELDS="leader_x_coord leader_y_coord leader_direction walking_style party_count"
{
  printf '.INCLUDE "config.asm"\n.INCLUDE "enums.asm"\n.INCLUDE "hardware.asm"\n.INCLUDE "structs.asm"\n'
  for f in $FIELDS; do printf '.out .sprintf("%s %%d", game_state::%s)\n' "$f" "$f"; done
} > "$WORK/fields.asm"
(cd "$WORK/ebsrc" && "$WORK/cc65/bin/ca65" -t none --cpu 65816 -D USA \
    --include-dir include --include-dir src -o /dev/null "$WORK/fields.asm") > "$WORK/fields.txt"

python3 - "$WORK/labels.txt" "$WORK/fields.txt" "$ROOT/src/eb_ram.h" <<'PY'
import sys
labels = {}
for line in open(sys.argv[1]):
    _, addr, name = line.split()
    labels[name.lstrip('.')] = int(addr, 16)

# Symbols we use, plus fields inside the game_state struct.
wanted = ["FRAME_COUNTER", "BATTLE_MODE", "BATTLE_MODE_FLAG", "CURRENT_LEADER_DIRECTION",
          "CURRENT_LEADING_PARTY_MEMBER_ENTITY", "PLAYER_POSITION_BUFFER", "PLAYER_MOVEMENT_FLAGS",
          "LAST_SECTOR_X", "LAST_SECTOR_Y", "INTERACTING_NPC_ID", "GAME_STATE"]
offsets = dict((l.split()[0], int(l.split()[1])) for l in open(sys.argv[2]))
fields = {"LEADER_X": offsets["leader_x_coord"], "LEADER_Y": offsets["leader_y_coord"],
          "LEADER_DIRECTION": offsets["leader_direction"], "WALKING_STYLE": offsets["walking_style"],
          "PARTY_COUNT": offsets["party_count"]}

out = ["/* Generated by tools/gen_ram_symbols.sh from the ebsrc disassembly (US EarthBound). Do not edit. */",
       "/* Values are SNES addresses; WRAM offset = addr - 0x7E0000. */",
       "#pragma once", ""]
for n in wanted:
    out.append(f"#define EB_{n:<40} 0x{labels[n]:06X}")
out.append("")
for n, off in fields.items():
    out.append(f"#define EB_{n:<40} 0x{labels['GAME_STATE'] + off:06X} /* GAME_STATE + {off} */")
out.append("")
out.append("#define EB_WRAM_OFFSET(addr) ((addr) - 0x7E0000)")
open(sys.argv[3], "w").write("\n".join(out) + "\n")
PY
echo "wrote src/eb_ram.h"
